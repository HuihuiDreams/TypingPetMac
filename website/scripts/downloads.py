"""Canonical download entry points and validated, release-pinned nginx targets."""
import re

IMMUTABLE_CACHE = 'public, max-age=31536000, immutable'
DIRECT = 'https://pet.miel.ing/update/production/'
GITHUB = 'https://github.com/ynifamily3/TypingPetMac/releases/download/'


def latest_url(source, kind):
    if source not in ('github', 'direct') or kind not in ('zip', 'dmg'):
        raise ValueError('Unknown download source or format')
    return f'https://pet.miel.ing/latest?from={source}&type={kind}'


def download_targets(metadata):
    """Accept only this repository's fixed asset URLs, never request-supplied URLs."""
    version, build = metadata['version'], metadata['build']
    if not re.fullmatch(r'\d+\.\d+\.\d+', version) or type(build) is not int or build < 1:
        raise ValueError('Invalid release version or build')
    github_prefix = f'{GITHUB}v{version}/'
    if (metadata['url'] != f'{DIRECT}TypingPet-{version}-{build}-arm64.zip'
            or metadata['githubUrl'] != f'{github_prefix}TypingPetMac-v{version}-arm64.zip'):
        raise ValueError('Unexpected ZIP download destination')
    targets = {'github:zip': metadata['githubUrl'], 'direct:zip': metadata['url']}
    default_kind = 'zip'
    if dmg := metadata.get('dmg'):
        names = {f'TypingPetMac-v{version}-arm64.dmg', f'TypingPetMac-v{version}-arm64-installer.dmg'}
        name = dmg['url'].rsplit('/', 1)[-1]
        if name not in names or dmg['url'] != DIRECT + name or dmg['githubUrl'] != github_prefix + name:
            raise ValueError('Unexpected DMG download destination')
        targets.update({'github:dmg': dmg['githubUrl'], 'direct:dmg': dmg['url']})
        default_kind = 'dmg'
    for source in ('github', 'direct'):
        targets[f'{source}:auto'] = targets[f'{source}:{default_kind}']
    return targets


def render_targets(metadata):
    targets = download_targets(metadata)
    lines = ['# Generated by typing-pet-mac/website/scripts/deploy.py; publish all targets together.',
             'map "$typing_pet_download_source:$typing_pet_download_type" $typing_pet_latest_target {',
             '    default "";']
    lines.extend(f'    "{key}" "{value}";' for key, value in targets.items())
    return ('\n'.join([*lines, '}', ''])).encode()
