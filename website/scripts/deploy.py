#!/usr/bin/env python3
"""Publish a verified static build and its release-pinned download routes on this Mac."""
import fcntl
import hashlib
import json
import os
from pathlib import Path
import re
import shutil
import subprocess
import tempfile
import sys
from datetime import datetime, timezone
from downloads import download_targets, render_targets

WEBSITE = Path(__file__).resolve().parents[1]
HOME = Path.home()
DESTINATION = HOME / 'server/typing-pet-site'
NGINX_CONFIG = HOME / '.config/nginx/nginx.conf'
SITE_CONFIG = HOME / '.config/nginx/conf.d/typing-pet-site.conf'
DOWNLOAD_CONFIG = HOME / '.config/nginx/conf.d/typing-pet.conf'
DOWNLOAD_TARGETS = HOME / '.config/nginx/snippets/typing-pet-download-targets.conf'
REDIRECT = HOME / '.config/nginx/snippets/typing-pet-latest.conf'
NGINX = '/opt/homebrew/bin/nginx'

def atomic_write(path, data):
    path.parent.mkdir(parents=True, exist_ok=True)
    with tempfile.NamedTemporaryFile(dir=path.parent, delete=False) as file:
        name = Path(file.name)
        file.write(data)
    os.chmod(name, 0o644)
    os.replace(name, path)

def run(*args):
    subprocess.run(args, check=True)

def restore_file(path, data):
    if data is None:
        path.unlink(missing_ok=True)
    else:
        atomic_write(path, data)

def reload_nginx():
    run(NGINX, '-t', '-c', str(NGINX_CONFIG))
    run(NGINX, '-s', 'reload', '-c', str(NGINX_CONFIG))

def redirect_only():
    """Keep the download alias current even for releases published without GitHub."""
    if not REDIRECT.is_file():
        return
    feed_path = HOME / 'TypingPetUpdate/production/latest.json'
    DESTINATION.mkdir(parents=True, exist_ok=True)
    with (DESTINATION / '.deploy.lock').open('a') as lock, (feed_path.parent / '.deploy.lock').open('a') as feed_lock:
        fcntl.flock(lock, fcntl.LOCK_EX | fcntl.LOCK_NB)
        fcntl.flock(feed_lock, fcntl.LOCK_EX | fcntl.LOCK_NB)
        feed = json.loads(feed_path.read_text())
        expected = f'https://pet.miel.ing/update/production/TypingPet-{feed["version"]}-{feed["build"]}-arm64.zip'
        if (feed['url'] != expected or not re.fullmatch(r'\d+\.\d+\.\d+', feed['version'])
                or type(feed['build']) is not int or not re.fullmatch(r'[a-f0-9]{64}', feed['sha256'])):
            raise RuntimeError('Unexpected update feed')
        archive = feed_path.parent / expected.rsplit('/', 1)[1]
        if hashlib.sha256(archive.read_bytes()).hexdigest() != feed['sha256']:
            raise RuntimeError('Archive digest does not match feed')
        new = f'# Generated by typing-pet-mac/website/scripts/deploy.py\nreturn 302 {expected};\n'.encode()
        old = REDIRECT.read_bytes()
        if old == new:
            print('Latest download redirect already matches the production feed.')
            return
        stamp = datetime.now(timezone.utc).strftime('%Y%m%dT%H%M%S%fZ')
        backup = DESTINATION / 'backups' / f'redirect-{stamp}'
        backup.mkdir(parents=True)
        (backup / 'typing-pet-latest.conf').write_bytes(old)
        try:
            atomic_write(REDIRECT, new)
            reload_nginx()
        except BaseException:
            atomic_write(REDIRECT, old)
            reload_nginx()
            raise
        print(f'Latest download redirect refreshed: {expected}')

def main():
    metadata = json.loads((WEBSITE / 'src/generated/release.json').read_text())
    targets = download_targets(metadata)
    feed_path = HOME / 'TypingPetUpdate/production/latest.json'
    feed_bytes = feed_path.read_bytes()
    feed = json.loads(feed_bytes)
    if any(metadata[k] != feed[k] for k in ('version', 'build', 'url', 'sha256', 'size')):
        raise RuntimeError('The update feed changed since the website build; sync and build again.')
    if not re.fullmatch(r'https://pet\.miel\.ing/update/production/TypingPet-\d+\.\d+\.\d+-\d+-arm64\.zip', feed['url']):
        raise RuntimeError('Unexpected redirect destination')
    archive = feed_path.parent / feed['url'].rsplit('/', 1)[1]
    if hashlib.sha256(archive.read_bytes()).hexdigest() != feed['sha256']:
        raise RuntimeError('Published archive does not match its feed')
    if dmg := metadata.get('dmg'):
        prefix = f'TypingPetMac-v{feed["version"]}-arm64'
        name = dmg['url'].rsplit('/', 1)[1]
        if name not in {f'{prefix}.dmg', f'{prefix}-installer.dmg'} or dmg['url'] != f'https://pet.miel.ing/update/production/{name}':
            raise RuntimeError('Unexpected DMG URL')
        disk_image = feed_path.parent / name
        if disk_image.stat().st_size != dmg['size'] or hashlib.sha256(disk_image.read_bytes()).hexdigest() != dmg['sha256']:
            raise RuntimeError('Published DMG differs from the GitHub-verified build')
    locales = json.loads((WEBSITE / 'src/locales.json').read_text())
    pages = [f'{locale}/{suffix}index.html' for locale in locales for suffix in ('', 'changelog/')]
    for path in [*pages, 'assets/social-preview.png']:
        if not (WEBSITE / 'dist' / path).is_file():
            raise RuntimeError(f'Missing site artifact: {path}')
    DESTINATION.mkdir(parents=True, exist_ok=True)
    with (DESTINATION / '.deploy.lock').open('a') as lock, (feed_path.parent / '.deploy.lock').open('a') as feed_lock:
        fcntl.flock(lock, fcntl.LOCK_EX | fcntl.LOCK_NB)
        fcntl.flock(feed_lock, fcntl.LOCK_EX | fcntl.LOCK_NB)
        if feed_path.read_bytes() != feed_bytes:
            raise RuntimeError('An app release changed the feed; retry the website publication.')
        stamp = datetime.now(timezone.utc).strftime('%Y%m%dT%H%M%S%fZ')
        release_dir = DESTINATION / 'releases' / f'{stamp}-v{feed["version"]}'
        shutil.copytree(WEBSITE / 'dist', release_dir)
        (release_dir / 'release.json').write_text(json.dumps(metadata, indent=2) + '\n')
        current = DESTINATION / 'current'
        previous = os.readlink(current) if current.is_symlink() else None
        configs = {
            DOWNLOAD_TARGETS: render_targets(metadata),
            DOWNLOAD_CONFIG: (WEBSITE / 'nginx/typing-pet-downloads.conf').read_bytes(),
            SITE_CONFIG: (WEBSITE / 'nginx/typing-pet-site.conf').read_bytes(),
            REDIRECT: f'# Generated by typing-pet-mac/website/scripts/deploy.py\nreturn 302 {feed["url"]};\n'.encode(),
        }
        old_configs = {path: path.read_bytes() if path.exists() else None for path in configs}
        backup = DESTINATION / 'backups' / stamp
        backup.mkdir(parents=True)
        for path, data in old_configs.items():
            if data is not None:
                (backup / path.name).write_bytes(data)
        (backup / 'previous.json').write_text(json.dumps({
            'current': previous, 'version': feed['version'],
            'absent_configs': [str(path) for path, data in old_configs.items() if data is None],
        }) + '\n')
        pending = DESTINATION / f'.current-{stamp}'
        try:
            for path, data in configs.items():
                atomic_write(path, data)
            # Make the entry points available before exposing buttons that use them.
            reload_nginx()
            pending.symlink_to(release_dir)
            os.replace(pending, current)
        except BaseException:
            pending.unlink(missing_ok=True)
            if previous:
                pending.symlink_to(previous)
                os.replace(pending, current)
            elif current.is_symlink():
                current.unlink()
            for path, data in old_configs.items():
                restore_file(path, data)
            reload_nginx()
            raise
        print(f'Published https://typing-pet.miel.ing/ — v{feed["version"]} ({feed["build"]})')
        print(f'Latest: 302 no-store, {len(targets) - 2} source/format targets; default GitHub DMG when available.')
        print(f'Previous build and nginx configuration retained in {backup}')

if __name__ == '__main__':
    if sys.argv[1:] == ['--redirect-only']:
        redirect_only()
    elif sys.argv[1:]:
        raise SystemExit('Usage: deploy.py [--redirect-only]')
    else:
        main()
